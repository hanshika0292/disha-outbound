#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE ROLE disha_admin LOGIN PASSWORD '${DISHA_ADMIN_PASSWORD}' BYPASSRLS CREATEDB;
  CREATE ROLE disha_app   LOGIN PASSWORD '${DISHA_APP_PASSWORD}'   NOBYPASSRLS;

  GRANT ALL     ON DATABASE "${POSTGRES_DB}" TO disha_admin;
  GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO disha_app;

  GRANT USAGE  ON SCHEMA public TO disha_app;
  GRANT CREATE ON SCHEMA public TO disha_admin;

  ALTER DEFAULT PRIVILEGES FOR ROLE disha_admin IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO disha_app;
  ALTER DEFAULT PRIVILEGES FOR ROLE disha_admin IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO disha_app;
EOSQL
